#!/bin/sh
# ============================================================================
# Alpindroid: adapt the Wayland stack to whatever head is actually connected
#
# Nothing here is hard-coded to one panel:
#   * the output name is read from DRM sysfs (`cardN-<NAME>/status == connected`)
#   * the mode stays `preferred`, i.e. whatever EDID asks for
#   * the touchscreen keeps its raw coordinate range (ABS_MT_POSITION_X/Y) and
#     libinput scales it onto the output, so a 1920x1080 panel on a 1024x600
#     head needs no calibration matrix
#
# What it writes
#   /etc/udev/rules.d/99-alpindroid-touch.rules   WL_OUTPUT=<detected head>
#   /etc/xdg/weston/weston.ini                    [output] name=<detected head>
#
# Run as root. Safe to re-run: it is invoked from install-wayland-stack.sh, from
# /etc/local.d on boot, and can be called by hand after plugging another screen:
#   sudo wayland-adapt.sh
#
# With no connected head (for example while building an image in a chroot) it
# removes the WL_OUTPUT rule instead of guessing, so Weston falls back to
# associating the touchscreen with the first enabled output.
# ============================================================================
set -u

RULES=/etc/udev/rules.d/99-alpindroid-touch.rules
INI=/etc/xdg/weston/weston.ini
VERBOSE="${VERBOSE:-1}"

say() { [ "$VERBOSE" = "1" ] && printf '%s\n' "$*"; return 0; }

detect_output() {
    # card0-HDMI-A-1 -> HDMI-A-1 ; ignores disconnected connectors
    for f in /sys/class/drm/card*-*/status; do
        [ -e "$f" ] || continue
        [ "$(cat "$f" 2>/dev/null)" = "connected" ] || continue
        n=$(basename "$(dirname "$f")")
        printf '%s\n' "${n#*-}"
        return 0
    done
    return 1
}

OUTPUT=$(detect_output 2>/dev/null) || OUTPUT=""

if [ -z "$OUTPUT" ]; then
    rm -f "$RULES"
    say "wayland-adapt: no connected head -> WL_OUTPUT rule removed (weston will pick the first enabled output)"
    exit 0
fi

say "wayland-adapt: connected head = $OUTPUT"

mkdir -p /etc/udev/rules.d
cat > "$RULES" <<EOF
# Generated by wayland-adapt.sh -- do not edit by hand.
# Binds every touchscreen to the head that is actually connected, so neither the
# connector name nor the panel resolution has to be hard-coded anywhere.
ACTION=="add|change", SUBSYSTEM=="input", KERNEL=="event*", ENV{ID_INPUT_TOUCHSCREEN}=="1", ENV{WL_OUTPUT}="$OUTPUT"
EOF
say "  wrote $RULES (WL_OUTPUT=$OUTPUT)"

if [ -f "$INI" ]; then
    if grep -q '^\[output\]' "$INI"; then
        tmp="$INI.tmp.$$"
        awk -v out="$OUTPUT" '
            BEGIN { inout = 0 }
            /^\[/ { inout = ($0 == "[output]") }
            inout && /^name=/ { print "name=" out; next }
            { print }
        ' "$INI" > "$tmp" && mv "$tmp" "$INI"
        say "  updated [output] name in $INI"
    else
        say "  no [output] section in $INI (weston already uses the preferred mode)"
    fi
fi

if command -v udevadm >/dev/null 2>&1; then
    udevadm control --reload >/dev/null 2>&1 || true
    udevadm trigger --subsystem-match=input >/dev/null 2>&1 || true
    udevadm settle >/dev/null 2>&1 || true
    # report what libinput/weston will see
    for e in /dev/input/event*; do
        [ -e "$e" ] || continue
        info=$(udevadm info "$e" 2>/dev/null) || continue
        case "$info" in
            *ID_INPUT_TOUCHSCREEN=1*)
                wl=$(printf '%s\n' "$info" | sed -n 's/^E: WL_OUTPUT=//p' | head -n 1)
                say "  $(basename "$e"): WL_OUTPUT=${wl:-unset}"
                ;;
        esac
    done
fi

say "wayland-adapt: done (mode stays 'preferred', touch scaling stays with libinput)"
